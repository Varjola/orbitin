/** Catalogue failures in plain words. The technical
 *  detail (`failure.message`, an HTTP status) goes to the console only. */
function catalogueError(failure: CatalogueFailure): string {
  switch (failure.kind) {
    case 'unavailable':
    case 'http':
    case 'unknown': return 'The satellite catalogue could not be loaded. Check your connection and try again.'
    case 'refresh-failed': return 'A newer satellite catalogue could not be loaded. The last one is still in use.'
    case 'invalid': return 'The satellite catalogue could not be read. Try again in a moment.'
    case 'not-loaded': return 'Load the satellite catalogue first.'
    case 'not-indexed': return 'This object is not in the current satellite catalogue.'
    case 'disposed':
    case 'closed': return 'The satellite catalogue was closed.'
    case 'snapshot-changed': return 'The satellite catalogue was updated while loading. Try again.'
  }
}
