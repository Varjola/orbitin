const ARCSEC_TO_RAD = Math.PI / (180 * 3600)
const U_TO_RAD = ARCSEC_TO_RAD * 0.0001
const TAU = Math.PI * 2

function wrap(rad: number): number { return ((rad % TAU) + TAU) % TAU }
function fundamentalArguments(T: number): readonly [number, number, number, number, number] {
  const T2 = T * T, T3 = T2 * T, T4 = T3 * T
  const arcsec = (base: number, a: number, b: number, c: number, d: number): number => wrap((base + a * T + b * T2 + c * T3 + d * T4) * ARCSEC_TO_RAD)
  return [
    arcsec(485868.249036, 1717915923.2178, 31.8792, 0.051635, -0.00024470),
    arcsec(1287104.79305, 129596581.0481, -0.5532, 0.000136, -0.00001149),
    arcsec(335779.526232, 1739527262.8478, -12.7512, -0.001037, 0.00000417),
    arcsec(1072260.70369, 1602961601.2090, -6.3706, 0.006593, -0.00003169),
    arcsec(450160.398036, -6962890.5431, 7.4722, 0.007702, -0.00005939),
  ]
}

export function iau1980NutationAt(instant: SimulationInstant): Iau1980Nutation {
  const T = julianCenturiesSinceJ2000(instant), T2 = T * T, T3 = T2 * T
  const [l, lp, f, d, omega] = fundamentalArguments(T)
  let deltaPsiRad = 0, deltaEpsilonRad = 0
  for (const [nl, nlp, nf, nd, nom, sp, spt, ce, cet] of TERMS) {
    const argument = nl * l + nlp * lp + nf * f + nd * d + nom * omega
    deltaPsiRad += (sp + spt * T) * U_TO_RAD * Math.sin(argument)
    deltaEpsilonRad += (ce + cet * T) * U_TO_RAD * Math.cos(argument)
  }
  const meanObliquityRad = degToRad((84381.448 - 46.8150 * T - 0.00059 * T2 + 0.001813 * T3) / 3600)
  return { deltaPsiRad, deltaEpsilonRad, meanObliquityRad, trueObliquityRad: meanObliquityRad + deltaEpsilonRad }
}

export const iau1980Nutation = iau1980NutationAt
